package com.quemsi.model.flow.db.cross;

import static org.hamcrest.MatcherAssert.assertThat;
import static org.hamcrest.Matchers.containsString;
import static org.hamcrest.Matchers.not;

import java.util.List;

import org.junit.jupiter.api.Test;

import com.quemsi.model.flow.db.mysql.DDLServiceMysql;
import com.quemsi.model.flow.db.oracle.DDLServiceOracle;
import com.quemsi.model.flow.db.postgres.DDLServicePostgres;
import com.quemsi.model.flow.db.sql.DbColumn;
import com.quemsi.model.flow.db.sql.DbModel;
import com.quemsi.model.flow.db.sql.DbTable;
import com.quemsi.model.flow.db.sql.diff.DbModelDiff;
import com.quemsi.model.flow.db.sql.diff.DbTableDiffOp;
import com.quemsi.model.flow.db.sql.diff.DiffOpType;

public class IdentityDdlTest {

	@Test
	public void postgresEmitsIdentityOnlyWhenFlagged() {
		String sql = postgresCreate(true);
		assertThat(sql, containsString("GENERATED BY DEFAULT AS IDENTITY"));
		assertThat(postgresCreate(false), not(containsString("GENERATED BY DEFAULT AS IDENTITY")));
	}

	@Test
	public void oracleEmitsIdentityOnlyWhenFlagged() {
		String sql = oracleCreate(true);
		assertThat(sql, containsString("GENERATED BY DEFAULT AS IDENTITY"));
		assertThat(oracleCreate(false), not(containsString("GENERATED BY DEFAULT AS IDENTITY")));
	}

	@Test
	public void mysqlAppendsAutoIncrementOnlyWhenFlagged() {
		String sql = mysqlCreate(true);
		assertThat(sql, containsString("AUTO_INCREMENT"));
		assertThat(mysqlCreate(false), not(containsString("AUTO_INCREMENT")));
	}

	@SuppressWarnings("resource")
	private static String postgresCreate(boolean identity) {
		DbTable table = new DbTable("public", "t");
		table.addColumn(DbColumn.builder().name("id").columnType("int4").dataType("int4")
			.ordinalPosition(1).nullable(false).identity(identity).build());
		return createSql(new DDLServicePostgres().ddlFrom(diff(table), new DbModel()));
	}

	@SuppressWarnings("resource")
	private static String oracleCreate(boolean identity) {
		DbTable table = new DbTable("HR", "T");
		table.addColumn(DbColumn.builder().name("ID").dataType("number").columnType("number")
			.ordinalPosition(1).numPrecision(19).numScale(0).nullable(false).identity(identity).build());
		return createSql(new DDLServiceOracle().ddlFrom(diff(table), new DbModel()));
	}

	@SuppressWarnings("resource")
	private static String mysqlCreate(boolean identity) {
		DbTable table = new DbTable(null, "t");
		table.addColumn(DbColumn.builder().name("id").columnType("bigint").dataType("bigint")
			.ordinalPosition(1).nullable(false).identity(identity).build());
		return createSql(new DDLServiceMysql().ddlFrom(diff(table), new DbModel()));
	}

	private static DbModelDiff diff(DbTable table) {
		DbModelDiff diff = new DbModelDiff();
		diff.getOperations().add(DbTableDiffOp.builder()
			.opType(DiffOpType.CREATE)
			.qualifiedName(table.qualifiedName())
			.newTable(table)
			.build());
		return diff;
	}

	private static String createSql(List<String> statements) {
		return String.join("\n", statements);
	}
}
